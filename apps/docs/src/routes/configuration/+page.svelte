      <pre><code>{`- name: Run ELCODE Forge PR Gate & SARIF Scan
  id: forge
  uses: elcode-id/elcode-forge/integrations/github-action@v1.0.0
  with:
    command: scan               # doctor | scan | review | diff | security | dependencies | graph
    path: .
    base: origin/main           # Base git ref when running review / ai-review
    format: terminal            # terminal | json | sarif | markdown
    strict: "true"              # Fails on high/critical findings when fail-on is unset
    fail-on: high               # critical | high | medium | low
    sarif-output: eforge.sarif  # Emits SARIF v2.1.0 file for scan or security commands
    ai-review: "false"          # Opt-in AI review (default: false)
    step-summary: "true"        # Appends Markdown report to $GITHUB_STEP_SUMMARY`}</code></pre>
