    </h2>
    <p class="text-sm text-slate-300 leading-relaxed">
      All local caches, OSV advisory databases, historical commit snapshots, and AI usage ledgers are stored inside <code class="text-blue-300 font-mono">&lt;repo_root&gt;/.eforge/</code> (automatically ignored during scans; add <code class="text-slate-200 font-mono">.eforge/</code> to your <code class="text-slate-200 font-mono">.gitignore</code> except <code class="text-slate-200 font-mono">.eforge/rules/</code> if you version custom rules there):
    </p>
    <div class="bg-black/50 border border-slate-800 rounded-lg p-4 font-mono text-xs overflow-x-auto text-slate-300">
      <pre><code>{`.eforge/
├── metadata.json          # BLAKE3 file content hashes, config_hash & analyzer_version for incremental scans
├── baseline.json          # Cached remote baseline snapshot pulled via 'eforge pull' or 'eforge sync'
├── ai-usage.jsonl         # Append-only daily token & USD cost ledger read by 'eforge ai usage'
├── ai-cache/              # Deterministic 64-char BLAKE3 response cache (<hash>.json, zero auth headers)
├── cache/
│   └── osv/               # Offline OSV vulnerability advisory cache per ecosystem (npm.json, pypi.json, etc.)
├── index/                 # Local AST & architecture graph index artifacts
├── history/               # Idempotent per-commit snapshots (<unix_ts>-<sha12>.json) via 'eforge report --save-history'
└── rules/
    └── custom-rules.yaml  # Declarative custom rules initialized via 'eforge rules init'`}</code></pre>
