/// A claim or risk generated by the AI model with deterministic fact-checking metadata.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct GroundedClaim {
    /// The claim, risk description, or suggestion.
    pub text: String,
    /// The source identifier cited by the AI (e.g. module ID, file path, finding ID).
    pub source: String,
    /// Whether this source identifier exists in the analyzed repository facts.
    #[serde(default)]
    pub verified: bool,
}

/// Structured AI interpretation for `eforge explain --ai`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct AiExplainAnswer {
    /// Executive summary of the target's architectural role.
    pub summary: String,
    /// Primary architectural responsibilities.
    pub responsibilities: Vec<String>,
    /// Critical outgoing and incoming module dependencies.
    pub key_dependencies: Vec<String>,
    /// Identified architectural risks, security concerns, or antipatterns.
    pub risks: Vec<GroundedClaim>,
    /// Cited facts and files used in the interpretation.
    pub sources: Vec<String>,
}

/// Metadata and answer for an AI-augmented explain execution.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct AiExplainOutput {
    /// Name of the AI provider (e.g. "openai", "anthropic", "gemini", "mock").
    pub provider: String,
    /// Model used for completion.
    pub model: String,
    /// Whether this answer was retrieved from local response cache.
    pub cached: bool,
    /// Token usage metrics for prompt and completion.
    pub token_usage: TokenUsage,
    /// Incurred cost in USD if unit pricing was configured.
    pub cost_usd: Option<f64>,
    /// Structured response from the model.
    pub answer: AiExplainAnswer,
}

/// CLI options governing AI execution.
#[derive(Debug, Clone, Default)]
pub struct AiExplainOptions {
    /// Augment structural explanation with AI interpretation.
    pub ai: bool,
    /// AI provider override (`openai`, `anthropic`, `gemini`, `mock`).
    pub provider: Option<String>,
    /// Model identifier override.
    pub model: Option<String>,
    /// Output context pack and token estimates without calling AI provider.
    pub dry_run: bool,
    /// Bypass AI response cache.
    pub no_cache: bool,
}

/// Determines whether a candidate file path is sensitive and must be excluded from AI context.
#[must_use]
pub fn is_sensitive_path(path: &str) -> bool {
    let normalized = path.replace('\\', "/");
    let lower = normalized.to_lowercase();
    let file_name = lower.rsplit('/').next().unwrap_or(&lower);

    if file_name.starts_with(".env") {
        return true;
    }
    if file_name.ends_with(".pem")
        || file_name.ends_with(".key")
        || file_name.ends_with(".pfx")
        || file_name.ends_with(".p12")
    {
        return true;
    }
    if lower.starts_with(".git/")
        || lower.contains("/.git/")
        || lower.starts_with(".eforge/")
        || lower.contains("/.eforge/")
    {
        return true;
    }
    false
}

/// Verifies whether `source` cited by the AI matches a known fact in the repository.
#[must_use]
pub fn verify_claim_source(source: &str, repo: &Repository) -> bool {
    let trimmed = source.trim().replace('\\', "/");
    if trimmed.is_empty() {
        return false;
    }

    // Check modules (id or root_path)
    if repo
        .modules
        .iter()
        .any(|m| m.id == trimmed || m.root_path == trimmed)
    {
        return true;
    }

    // Check files
    if repo.files.iter().any(|f| f.relative_path == trimmed) {
        return true;
    }

    // Check findings (id or rule_id)
    if repo
        .findings
        .iter()
        .any(|f| f.id == trimmed || f.rule_id == trimmed)
    {
        return true;
    }

    false
}

/// Converts UNIX timestamp to `YYYY-MM-DD` date string deterministically without external crates.
#[must_use]
pub fn current_utc_date() -> String {
    let now = std::time::SystemTime::now();
    let duration = now
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap_or_default();
    let mut days = (duration.as_secs() / 86400) as i64;

    let mut year = 1970;
    loop {
        let leap = (year % 4 == 0 && year % 100 != 0) || (year % 400 == 0);
        let days_in_year = if leap { 366 } else { 365 };
        if days < days_in_year {
            break;
        }
        days -= days_in_year;
        year += 1;
    }

    let leap = (year % 4 == 0 && year % 100 != 0) || (year % 400 == 0);
    let days_in_months = [
        31,
        if leap { 29 } else { 28 },
        31,
        30,
        31,
        30,
        31,
        31,
        30,
        31,
        30,
        31,
    ];
    let mut month = 1;
    for &dim in &days_in_months {
        if days < dim {
            break;
        }
        days -= dim;
        month += 1;
    }

    format!("{year:04}-{month:02}-{:02}", days + 1)
}

/// Reads up to 5 relevant source code snippets for `target`, redacting any hardcoded secrets.
pub fn collect_safe_snippets(
    repo_root: &Path,
    repo: &Repository,
    target: &str,
) -> Result<Vec<CodeSnippet>, ForgeError> {
    let canonical_root = repo_root.canonicalize().map_err(|source| ForgeError::Io {
        path: repo_root.to_path_buf(),
        source,
    })?;

    let mut snippets = Vec::new();
    let mut count = 0;

    for file in &repo.files {
        if is_sensitive_path(&file.relative_path) {
            continue;
        }

        // Match target module or file
        let matches = if target.is_empty() || target == "." {
            true
        } else {
            file.relative_path == target
                || file
                    .relative_path
                    .strip_prefix(target)
                    .is_some_and(|rest| rest.starts_with('/'))
        };

        if !matches {
            continue;
        }

        let full_path = repo_root.join(&file.relative_path);
        let Ok(canonical_file) = full_path.canonicalize() else {
            continue;
        };

        if !canonical_file.starts_with(&canonical_root) {
            continue;
        }

        let Ok(raw_content) = fs::read_to_string(&canonical_file) else {
            continue;
        };

        let redacted = redact_secrets(&raw_content);
        let lines: Vec<&str> = redacted.lines().take(100).collect();
        let line_count = lines.len() as u32;
        let snippet_content = lines.join("\n");

        snippets.push(CodeSnippet::new(
            file.relative_path.clone(),
            1,
            line_count,
            snippet_content,
        ));

        count += 1;
        if count >= 5 {
            break;
        }
    }

    Ok(snippets)
}

/// JSON Schema definition for [`AiExplainAnswer`].
#[must_use]
pub fn explain_response_schema() -> serde_json::Value {
    serde_json::json!({
        "type": "object",
        "properties": {
            "summary": { "type": "string" },
            "responsibilities": {
                "type": "array",
                "items": { "type": "string" }
            },
            "key_dependencies": {
                "type": "array",
                "items": { "type": "string" }
            },
            "risks": {
                "type": "array",
                "items": {
                    "type": "object",
                    "properties": {
                        "text": { "type": "string" },
                        "source": { "type": "string" }
                    },
                    "required": ["text", "source"],
                    "additionalProperties": false
                }
            },
            "sources": {
                "type": "array",
                "items": { "type": "string" }
            }
        },
        "required": ["summary", "responsibilities", "key_dependencies", "risks", "sources"],
        "additionalProperties": false
    })
}

/// Result of AI explain execution: either a DryRun context pack or full AI output.
pub enum ExplainAiResult {
    DryRun(ContextPack),
    Output(AiExplainOutput),
}

/// Executes AI augmentation for `eforge explain`.
pub fn execute_explain_ai(
    repo_root: &Path,
    repo: &Repository,
    target: &str,
    opts: &AiExplainOptions,
) -> Result<ExplainAiResult, ForgeError> {
    let forge_cfg = load_config(repo_root).unwrap_or_default();
    let mut ai_cfg = forge_cfg.ai;

    let is_mock_override = opts
        .provider
        .as_deref()
        .map(|p| p.eq_ignore_ascii_case("mock"))
        .unwrap_or(false);

    // Apply CLI overrides
    if let Some(ref p) = opts.provider {
        if is_mock_override {
            ai_cfg.enabled = true;
        } else {
            match p.to_lowercase().as_str() {
                "openai" | "openai-compatible" => {
                    ai_cfg.provider = Some(AiProviderKind::OpenAiCompatible)
                }
                "anthropic" => ai_cfg.provider = Some(AiProviderKind::Anthropic),
                "gemini" => ai_cfg.provider = Some(AiProviderKind::Gemini),
                other => {
                    return Err(ForgeError::Config {
                        message: format!("unsupported AI provider override '{other}'"),
                    })
                }
            }
        }
    }
    if let Some(ref m) = opts.model {
        ai_cfg.model = Some(m.clone());
    }

    // Collect candidate facts & safe snippets
    let snippets = collect_safe_snippets(repo_root, repo, target)?;
    let sections = sections_from_repository(repo, Some(target));

    let input = ContextInput {
        task: AiTask::ExplainModule,
        sections,
        snippets,
    };

    let pack = build_context(&input, ai_cfg.max_context_tokens)?;

    // Handle Dry Run (zero provider calls, zero caching)
    if opts.dry_run {
        return Ok(ExplainAiResult::DryRun(pack));
    }

    // Verify AI feature is enabled
    ensure_ai_enabled(&ai_cfg)?;

    let today = current_utc_date();
    let provider_name = if is_mock_override {
        "mock".to_string()
    } else {
        match ai_cfg.provider {
            Some(AiProviderKind::OpenAiCompatible) => "openai-compatible".to_string(),
            Some(AiProviderKind::Anthropic) => "anthropic".to_string(),
            Some(AiProviderKind::Gemini) => "gemini".to_string(),
            None => "openai-compatible".to_string(),
        }
    };
    let model_name = ai_cfg
        .model
        .clone()
        .unwrap_or_else(|| "gpt-4o-mini".to_string());
    let schema = explain_response_schema();
    let schema_str = serde_json::to_string(&schema).map_err(|e| ForgeError::Serialization {
        message: e.to_string(),
    })?;

    let cache = ResponseCache::new(repo_root);
    let cache_key = ResponseCache::key(
        &provider_name,
        &model_name,
        &pack.system_prompt,
        &pack.user_payload,
        Some(&schema_str),
    );

    // Check response cache
    if !opts.no_cache {
        if let Ok(Some(cached_val)) = cache.get(&cache_key) {
            if let Ok(mut answer) = serde_json::from_value::<AiExplainAnswer>(cached_val) {
                // Re-verify grounded claims against current repository facts
                for claim in &mut answer.risks {
                    claim.verified = verify_claim_source(&claim.source, repo);
                }

                let usage = UsageRecord {
                    date: today,
                    provider: provider_name.clone(),
                    model: model_name.clone(),
                    command: "explain".to_string(),
                    input_tokens: 0,
                    output_tokens: 0,
                    cost_usd: Some(0.0),
                    cached: true,
                };
                let _ = append_usage(repo_root, &usage);

                return Ok(ExplainAiResult::Output(AiExplainOutput {
                    provider: provider_name,
                    model: model_name,
                    cached: true,
                    token_usage: TokenUsage::new(0, 0),
                    cost_usd: Some(0.0),
                    answer,
                }));
            }
        }
    }

    // Enforce cost controls
    let summary = summarize_usage(repo_root, &today)?;
    enforce_daily_budget(&summary, &ai_cfg)?;
    preflight_check(&pack, &ai_cfg)?;

    // Build provider
    let provider: Box<dyn AiProvider> = if is_mock_override {
        let sample_answer = AiExplainAnswer {
            summary: format!("Mock architectural overview for target '{target}'."),
            responsibilities: vec!["Handles domain business logic".to_string()],
            key_dependencies: vec!["src/db".to_string()],
            risks: vec![GroundedClaim {
                text: "Potential tight coupling with database".to_string(),
                source: "src/db".to_string(),
                verified: true,
            }],
            sources: vec!["src/services".to_string()],
        };
        Box::new(
            MockProvider::new()
                .with_structured_output(serde_json::to_value(&sample_answer).map_err(|e| {
                    ForgeError::Serialization {
                        message: e.to_string(),
                    }
                })?)
                .with_model(&model_name),
        )
    } else {
        build_provider(&ai_cfg, &|k| std::env::var(k).ok())?
    };

    // Execute structured generation
    let req = AiRequest::new(
        &pack.system_prompt,
        vec![AiMessage::user(&pack.user_payload)],
    );
    let json_val = provider.structured_output(&req, &schema)?;

    let mut answer: AiExplainAnswer =
        serde_json::from_value(json_val.clone()).map_err(|e| ForgeError::Ai {
            message: format!("failed to parse structured model response as AiExplainAnswer: {e}"),
        })?;

    // Verify source citations
    for claim in &mut answer.risks {
        claim.verified = verify_claim_source(&claim.source, repo);
    }

    // Persist to response cache
    if !opts.no_cache {
        let _ = cache.put(&cache_key, &json_val);
    }

    // Calculate token usage & cost
    let out_json_str = serde_json::to_string(&json_val).unwrap_or_default();
    let output_tokens = estimate_tokens(&out_json_str);
    let token_usage = TokenUsage::new(pack.estimated_tokens, output_tokens);

    let cost_usd = compute_cost_usd(token_usage.input_tokens, token_usage.output_tokens, &ai_cfg);
    let usage = UsageRecord {
        date: today,
        provider: provider_name.clone(),
        model: model_name.clone(),
        command: "explain".to_string(),
        input_tokens: token_usage.input_tokens,
        output_tokens: token_usage.output_tokens,
        cost_usd,
        cached: false,
    };
    let _ = append_usage(repo_root, &usage);

    Ok(ExplainAiResult::Output(AiExplainOutput {
        provider: provider_name,
        model: model_name,
        cached: false,
        token_usage,
        cost_usd,
        answer,
    }))
}

#[cfg(test)]
mod tests {
    use super::*;
    use forge_core::FileNode;

    fn dummy_repository() -> Repository {
        Repository {
            root_path: ".".to_string(),
            name: "test-repo".to_string(),
            detected_languages: vec!["typescript".to_string()],
            detected_frameworks: Vec::new(),
            package_managers: Vec::new(),
            files: Vec::new(),
            modules: Vec::new(),
            dependencies: Vec::new(),
            findings: Vec::new(),
            health: None,
        }
    }

    #[test]
    fn sensitive_path_detector_identifies_credentials_and_internal_dirs() {
        assert!(is_sensitive_path(".env"));
        assert!(is_sensitive_path(".env.local"));
        assert!(is_sensitive_path(".env.production"));
        assert!(is_sensitive_path("config/certs/tls.pem"));
        assert!(is_sensitive_path("secrets/app.key"));
        assert!(is_sensitive_path(".git/HEAD"));
        assert!(is_sensitive_path(".eforge/cache/metadata.json"));

        assert!(!is_sensitive_path("src/index.ts"));
        assert!(!is_sensitive_path("package.json"));
        assert!(!is_sensitive_path("README.md"));
    }

    #[test]
    fn claim_source_verification_checks_modules_files_and_findings() {
        let mut repo = dummy_repository();
        repo.modules.push(forge_core::Module {
            id: "src/services".to_string(),
            name: "services".to_string(),
            root_path: "src/services".to_string(),
            files: vec!["src/services/user.ts".to_string()],
            imports: Vec::new(),
            exports: Vec::new(),
        });
        repo.files.push(FileNode {
            relative_path: "src/services/user.ts".to_string(),
            size_bytes: 120,
            line_count: 10,
            language: Some("typescript".to_string()),
            content_hash: "hash".to_string(),
            is_test: false,
        });
        repo.findings.push(forge_core::Finding {
            id: "SEC-001".to_string(),
            category: "security".to_string(),
            severity: forge_core::Severity::High,
            confidence: forge_core::Confidence::High,
            title: "SQL injection".to_string(),
            description: "desc".to_string(),
            evidence: "ev".to_string(),
            location: None,
            recommendation: "rec".to_string(),
            rule_id: "security/no-eval".to_string(),
        });

        assert!(verify_claim_source("src/services", &repo));
        assert!(verify_claim_source("src/services/user.ts", &repo));
        assert!(verify_claim_source("SEC-001", &repo));
        assert!(verify_claim_source("security/no-eval", &repo));

        // Hallucinated claims must fail verification
        assert!(!verify_claim_source("src/nonexistent", &repo));
        assert!(!verify_claim_source("SEC-999", &repo));
    }

    #[test]
    fn current_utc_date_produces_valid_iso_format() {
        let date = current_utc_date();
        assert_eq!(date.len(), 10);
        let parts: Vec<&str> = date.split('-').collect();
        assert_eq!(parts.len(), 3);
        assert_eq!(parts[0].len(), 4);
        assert_eq!(parts[1].len(), 2);
        assert_eq!(parts[2].len(), 2);
    }
}
