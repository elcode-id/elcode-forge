//! Native Git hook installation, status inspection, and lifecycle management.

use forge_core::ForgeError;
use serde::{Deserialize, Serialize};
use std::fs;
use std::path::{Path, PathBuf};

/// Marker comment placed at the top of ELCODE Forge generated hook scripts.
pub const FORGE_HOOK_MARKER_START: &str = "# === BEGIN ELCODE FORGE HOOK (https://elcode.id/) ===";
/// Marker comment placed at the bottom of ELCODE Forge generated hook scripts.
pub const FORGE_HOOK_MARKER_END: &str = "# === END ELCODE FORGE HOOK ===";
/// File extension used when backing up pre-existing foreign hook scripts.
pub const BACKUP_EXTENSION: &str = "forge-backup";

/// Supported Git hook types managed by ELCODE Forge.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum HookType {
    PreCommit,
    PrePush,
    All,
}

impl HookType {
    /// Returns the standard git hook file names associated with this hook type.
    pub fn filenames(&self) -> &'static [&'static str] {
        match self {
            HookType::PreCommit => &["pre-commit"],
            HookType::PrePush => &["pre-push"],
            HookType::All => &["pre-commit", "pre-push"],
        }
    }
}

/// Inspection status for an individual Git hook script.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct HookEntryStatus {
    pub hook_name: String,
    pub installed: bool,
    pub managed_by_forge: bool,
    pub has_backup: bool,
    pub path: PathBuf,
}

/// Full status report of all managed Git hooks in a repository.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct HookStatusReport {
    pub git_dir: PathBuf,
    pub hooks_dir: PathBuf,
    pub hooks: Vec<HookEntryStatus>,
}

/// Outcome of a hook installation operation.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Default)]
pub struct HookInstallResult {
    pub installed: Vec<String>,
    pub backed_up: Vec<String>,
    pub skipped: Vec<String>,
}

/// Outcome of a hook uninstallation operation.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Default)]
pub struct HookUninstallResult {
    pub uninstalled: Vec<String>,
    pub restored: Vec<String>,
    pub skipped: Vec<String>,
}

/// Generates a POSIX-compliant shell script for the given hook name.
pub fn generate_hook_script(hook_name: &str) -> String {
    format!(
        r#"#!/bin/sh
{FORGE_HOOK_MARKER_START}
# Product: ELCODE Forge (https://elcode.id/)
# Purpose: Fast deterministic codebase intelligence & architecture gate.
# This script was auto-generated by `eforge hook install`.
# To temporarily bypass this check, run: FORGE_SKIP_HOOK=1 git commit

if [ "$FORGE_SKIP_HOOK" = "1" ]; then
    exit 0
fi

# Locate `eforge` binary (PATH first, then fallback to local builds)
if command -v eforge >/dev/null 2>&1; then
    FORGE_BIN="eforge"
elif command -v elcode-forge >/dev/null 2>&1; then
    FORGE_BIN="elcode-forge"
elif [ -x "./target/release/eforge" ]; then
    FORGE_BIN="./target/release/eforge"
elif [ -x "./target/debug/eforge" ]; then
    FORGE_BIN="./target/debug/eforge"
else
    # Non-blocking warning if eforge is not found on machine
    echo "warning: [elcode-forge] binary 'eforge' not found on PATH. Skipping hook." >&2
    exit 0
fi

"$FORGE_BIN" hook run "{hook_name}"
HOOK_EXIT_CODE=$?

if [ $HOOK_EXIT_CODE -ne 0 ]; then
    echo "error: [elcode-forge] git hook '{hook_name}' failed with exit code $HOOK_EXIT_CODE." >&2
    exit $HOOK_EXIT_CODE
fi

exit 0
{FORGE_HOOK_MARKER_END}
"#
    )
}

/// Resolves the `.git/hooks/` directory for the given repository root.
pub fn resolve_hooks_dir(repo_root: &Path) -> Result<PathBuf, ForgeError> {
    let git_dir = repo_root.join(".git");
    if !git_dir.exists() {
        return Err(ForgeError::Analysis {
            analyzer: "forge-git",
            message: format!(
                "Directory '{}' is not a git repository (missing .git)",
                repo_root.display()
            ),
        });
    }

    // Handle git worktree or submodule where .git is a file containing `gitdir: <path>`
    if git_dir.is_file() {
        let content = fs::read_to_string(&git_dir).map_err(|source| ForgeError::Io {
            path: git_dir.clone(),
            source,
        })?;
        if let Some(rest) = content.strip_prefix("gitdir:") {
            let target_gitdir = rest.trim();
            let resolved = if Path::new(target_gitdir).is_absolute() {
                PathBuf::from(target_gitdir)
            } else {
                repo_root.join(target_gitdir)
            };
            return Ok(resolved.join("hooks"));
        }
    }

    Ok(git_dir.join("hooks"))
}

/// Inspects the status of managed Git hooks.
pub fn get_hooks_status(repo_root: &Path) -> Result<HookStatusReport, ForgeError> {
    let hooks_dir = resolve_hooks_dir(repo_root)?;
    let git_dir = repo_root.join(".git");
    let mut entries = Vec::new();

    for hook_name in HookType::All.filenames() {
        let hook_path = hooks_dir.join(hook_name);
        let backup_path = hooks_dir.join(format!("{hook_name}.{BACKUP_EXTENSION}"));

        let installed = hook_path.is_file();
        let has_backup = backup_path.is_file();
        let managed_by_forge = if installed {
            let content = fs::read_to_string(&hook_path).unwrap_or_default();
            content.contains(FORGE_HOOK_MARKER_START)
        } else {
            false
        };

        entries.push(HookEntryStatus {
            hook_name: hook_name.to_string(),
            installed,
            managed_by_forge,
            has_backup,
            path: hook_path,
        });
    }

    Ok(HookStatusReport {
        git_dir,
        hooks_dir,
        hooks: entries,
    })
}

/// Installs Git hooks non-destructively into `.git/hooks/`.
pub fn install_hooks(
    repo_root: &Path,
    hook_type: HookType,
    force: bool,
) -> Result<HookInstallResult, ForgeError> {
    let hooks_dir = resolve_hooks_dir(repo_root)?;
    if !hooks_dir.exists() {
        fs::create_dir_all(&hooks_dir).map_err(|source| ForgeError::Io {
            path: hooks_dir.clone(),
            source,
        })?;
    }

    let mut result = HookInstallResult::default();

    for hook_name in hook_type.filenames() {
        let hook_path = hooks_dir.join(hook_name);
        let backup_path = hooks_dir.join(format!("{hook_name}.{BACKUP_EXTENSION}"));

        if hook_path.exists() {
            let existing_content =
                fs::read_to_string(&hook_path).map_err(|source| ForgeError::Io {
                    path: hook_path.clone(),
                    source,
                })?;

            if existing_content.contains(FORGE_HOOK_MARKER_START) {
                if !force {
                    result.skipped.push(hook_name.to_string());
                    continue;
                }
            } else {
                // Existing foreign hook: back it up
                fs::copy(&hook_path, &backup_path).map_err(|source| ForgeError::Io {
                    path: backup_path.clone(),
                    source,
                })?;
                result.backed_up.push(hook_name.to_string());
            }
        }

        let script = generate_hook_script(hook_name);
        fs::write(&hook_path, script).map_err(|source| ForgeError::Io {
            path: hook_path.clone(),
            source,
        })?;

        // On Unix, set executable permission 0o755
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let permissions = fs::Permissions::from_mode(0o755);
            let _ = fs::set_permissions(&hook_path, permissions);
        }

        result.installed.push(hook_name.to_string());
    }

    Ok(result)
}

/// Uninstalls Git hooks and restores any existing `.forge-backup` hooks.
pub fn uninstall_hooks(
    repo_root: &Path,
    hook_type: HookType,
) -> Result<HookUninstallResult, ForgeError> {
    let hooks_dir = resolve_hooks_dir(repo_root)?;
    let mut result = HookUninstallResult::default();

    for hook_name in hook_type.filenames() {
        let hook_path = hooks_dir.join(hook_name);
        let backup_path = hooks_dir.join(format!("{hook_name}.{BACKUP_EXTENSION}"));

        if hook_path.exists() {
            let content = fs::read_to_string(&hook_path).map_err(|source| ForgeError::Io {
                path: hook_path.clone(),
                source,
            })?;

            if content.contains(FORGE_HOOK_MARKER_START) {
                fs::remove_file(&hook_path).map_err(|source| ForgeError::Io {
                    path: hook_path.clone(),
                    source,
                })?;
                result.uninstalled.push(hook_name.to_string());

                // If backup exists, restore it
                if backup_path.exists() {
                    fs::rename(&backup_path, &hook_path).map_err(|source| ForgeError::Io {
                        path: hook_path.clone(),
                        source,
                    })?;
                    result.restored.push(hook_name.to_string());
                }
            } else {
                // Not managed by forge, skip
                result.skipped.push(hook_name.to_string());
            }
        } else {
            result.skipped.push(hook_name.to_string());
        }
    }

    Ok(result)
}

#[cfg(test)]
mod tests {
    use super::*;

    struct TempDirGuard {
        path: PathBuf,
    }

    impl TempDirGuard {
        fn new(name: &str) -> Self {
            let mut path = std::env::temp_dir();
            let nonce = std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .map(|d| d.as_nanos())
                .unwrap_or(0);
            path.push(format!("eforge_git_hooks_{}_{}", name, nonce));
            let _ = fs::create_dir_all(&path);
            Self { path }
        }
    }

    impl Drop for TempDirGuard {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.path);
        }
    }

    #[test]
    fn errors_when_missing_git_directory() {
        let temp = TempDirGuard::new("no_git");
        let res = install_hooks(&temp.path, HookType::All, false);
        assert!(matches!(res, Err(ForgeError::Analysis { .. })));
    }

    #[test]
    fn installs_and_uninstalls_hooks_cleanly() {
        let temp = TempDirGuard::new("lifecycle");
        let git_dir = temp.path.join(".git");
        assert!(fs::create_dir_all(&git_dir).is_ok());

        // Install hooks
        let install_res = install_hooks(&temp.path, HookType::All, false);
        assert!(install_res.is_ok());
        if let Ok(res) = install_res {
            assert_eq!(res.installed, vec!["pre-commit", "pre-push"]);
            assert!(res.backed_up.is_empty());
            assert!(res.skipped.is_empty());
        }

        // Check status
        let status_res = get_hooks_status(&temp.path);
        assert!(status_res.is_ok());
        if let Ok(status) = status_res {
            assert_eq!(status.hooks.len(), 2);
            for h in &status.hooks {
                assert!(h.installed);
                assert!(h.managed_by_forge);
                assert!(!h.has_backup);
            }
        }

        // Re-install without force should skip
        let reinstall_res = install_hooks(&temp.path, HookType::All, false);
        assert!(reinstall_res.is_ok());
        if let Ok(res) = reinstall_res {
            assert!(res.installed.is_empty());
            assert_eq!(res.skipped, vec!["pre-commit", "pre-push"]);
        }

        // Re-install with force should overwrite
        let force_res = install_hooks(&temp.path, HookType::PreCommit, true);
        assert!(force_res.is_ok());
        if let Ok(res) = force_res {
            assert_eq!(res.installed, vec!["pre-commit"]);
        }

        // Uninstall hooks
        let uninstall_res = uninstall_hooks(&temp.path, HookType::All);
        assert!(uninstall_res.is_ok());
        if let Ok(res) = uninstall_res {
            assert_eq!(res.uninstalled, vec!["pre-commit", "pre-push"]);
            assert!(res.restored.is_empty());
        }

        // Status after uninstall
        let post_status = get_hooks_status(&temp.path);
        assert!(post_status.is_ok());
        if let Ok(status) = post_status {
            for h in &status.hooks {
                assert!(!h.installed);
                assert!(!h.managed_by_forge);
            }
        }
    }

    #[test]
    fn backs_up_foreign_hook_and_restores_on_uninstall() {
        let temp = TempDirGuard::new("foreign_hook");
        let hooks_dir = temp.path.join(".git").join("hooks");
        assert!(fs::create_dir_all(&hooks_dir).is_ok());

        let foreign_script = "#!/bin/sh\necho 'my custom linter'\n";
        let pre_commit_path = hooks_dir.join("pre-commit");
        assert!(fs::write(&pre_commit_path, foreign_script).is_ok());

        // Install forge hook
        let install_res = install_hooks(&temp.path, HookType::PreCommit, false);
        assert!(install_res.is_ok());
        if let Ok(res) = install_res {
            assert_eq!(res.installed, vec!["pre-commit"]);
            assert_eq!(res.backed_up, vec!["pre-commit"]);
        }

        // Check status shows backup exists
        let status = get_hooks_status(&temp.path);
        assert!(status.is_ok());
        if let Ok(rep) = status {
            let pre_commit = rep.hooks.iter().find(|h| h.hook_name == "pre-commit");
            assert!(pre_commit.is_some());
            if let Some(h) = pre_commit {
                assert!(h.installed);
                assert!(h.managed_by_forge);
                assert!(h.has_backup);
            }
        }

        // Uninstall should remove forge hook and restore the backup
        let uninstall_res = uninstall_hooks(&temp.path, HookType::PreCommit);
        assert!(uninstall_res.is_ok());
        if let Ok(res) = uninstall_res {
            assert_eq!(res.uninstalled, vec!["pre-commit"]);
            assert_eq!(res.restored, vec!["pre-commit"]);
        }

        // Verify the original script content is restored
        let restored_content = fs::read_to_string(&pre_commit_path);
        assert!(restored_content.is_ok());
        if let Ok(content) = restored_content {
            assert_eq!(content, foreign_script);
        }
    }
}
